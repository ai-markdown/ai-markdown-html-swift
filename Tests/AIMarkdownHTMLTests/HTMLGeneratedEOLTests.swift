import Foundation
import Testing
@testable import AIMarkdownHTML

struct HTMLGeneratedEOLTests {
    private struct Oracle: Decodable { let cases: [Item] }
    private struct Item: Decodable {
        let id: String; let segments: [SourceInputEmission]; let encodedSegments: [SourceInputEmission]
        let encodedRawSource: String; let semantic: SourceDOMNode
    }
    private func encoded<T: Encodable>(_ value: T) throws -> Data {
        let encoder = JSONEncoder(); encoder.outputFormatting = [.sortedKeys, .withoutEscapingSlashes]
        return try encoder.encode(value)
    }
    @MainActor @Test func generatedTextKeepsCRInCharactersAndEncodedRepresentations() throws {
        let url = try #require(Bundle.module.url(forResource: "html-generated-eol", withExtension: "json", subdirectory: "Fixtures"))
        let cases = try JSONDecoder().decode(Oracle.self, from: Data(contentsOf: url)).cases
        #expect(cases.count == 8)
        for item in cases {
            let characters = try HTMLSourceParser.parseFragment(item.segments, tracking: true)
            let parsed = try HTMLSourceParser.parseFragment(item.encodedSegments, tracking: true)
            let plain = try HTMLSourceParser.parseFragment(item.encodedSegments)
            let trace = try #require(parsed.trace)
            #expect(try encoded(trace.semantic) == encoded(item.semantic), "\(item.id): complete HAST tree generated by the Web implementation")
            #expect(try encoded(trace.semantic) == encoded(try #require(characters.trace).semantic), "\(item.id): both representations preserve the same generated semantics")
            #expect(try encoded(trace.semantic) == encoded(SourceEventRecorder(bytes: [], emissions: []).result(plain.roots).semantic))
            #expect(!trace.tokens.contains { $0.kind == "generated-characters" })
            let inputs = Dictionary(uniqueKeysWithValues: item.encodedSegments.map { ($0.id, $0) }), bytes = Array(item.encodedRawSource.utf8)
            let expectedCount = item.encodedSegments.filter { $0.role == "author-raw" }.reduce(0) { $0 + $1.value.utf8.filter { $0 == 13 }.count }
            #expect(trace.inputNormalizations.count == expectedCount)
            for piece in trace.inputNormalizations {
                #expect(piece.emissions.count == 1 && inputs[piece.emissions[0]]?.role == "author-raw")
                let range = try #require(piece.range)
                #expect(piece.bytes == [10] && [Array("\r".utf8), Array("\r\n".utf8)].contains(Array(bytes[range[0] ..< range[1]])))
            }
            for node in trace.nodes {
                for piece in node.pieces {
                    guard let range = piece.range else { continue }
                    #expect(range[0] >= 0 && range[1] <= bytes.count)
                    if piece.kind == "copy" { #expect(piece.bytes == Array(bytes[range[0] ..< range[1]])) }
                    #expect(!piece.emissions.contains { inputs[$0]?.role == "serialized-generated-text" } || piece.kind != "normalized-line-ending")
                }
                if let path = node.finalPath, ["#text", "#data"].contains(node.name) {
                    var semantic = trace.semantic
                    for index in path { semantic = try #require(semantic.children?[index]) }
                    #expect(node.pieces.flatMap(\.bytes) == Array((semantic.value ?? "").utf8))
                }
            }
        }
    }
}
